// Назва магазину в одному місці — щоб вона не була розкидана по листах і SMS.
// Змінити можна змінною середовища SHOP_NAME (за замовчуванням «В Хату.UA»).
const SHOP_NAME = process.env.SHOP_NAME || 'В Хату.UA';

// У SMS крапку між словом і «UA» прибираємо: оператори й антиспам-фільтри можуть прийняти
// «Хату.UA» за посилання, а SMS із посиланнями часто блокуються.
const SMS_BRAND = SHOP_NAME.replace(/\./g, ' ');

module.exports = { SHOP_NAME, SMS_BRAND };
