async function ensureDefaultPages() {
  for (const p of DEFAULT_PAGES) {
    await pool.query(
      `INSERT INTO site_pages (slug, title, content, sort_order, updated_by) VALUES ($1, $2, $3, $4, 'system')
       ON CONFLICT (slug) DO NOTHING`, [p.slug, p.title, p.content, p.sort_order]);
  }
}

async function liveSnapshot() {
  const owner = await getOwner();
  return buildSnapshot(owner.value);
}

async function renderPageRow(row) {
  const { html, toc } = renderTerms(row.content, await liveSnapshot());
  return { slug: row.slug, title: row.title, html, toc, updated_at: row.updated_at };
}

module.exports = { DEFAULT_PAGES, ensureDefaultPages, renderPageRow, liveSnapshot };
